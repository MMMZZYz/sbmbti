// 公历月日 → 星座（边界为各星座起始日）
const ZODIAC_BOUNDARY = {
  1:  [20, '水瓶座', '摩羯座'],
  2:  [19, '双鱼座', '水瓶座'],
  3:  [21, '白羊座', '双鱼座'],
  4:  [20, '金牛座', '白羊座'],
  5:  [21, '双子座', '金牛座'],
  6:  [22, '巨蟹座', '双子座'],
  7:  [23, '狮子座', '巨蟹座'],
  8:  [23, '处女座', '狮子座'],
  9:  [23, '天秤座', '处女座'],
  10: [24, '天蝎座', '天秤座'],
  11: [23, '射手座', '天蝎座'],
  12: [22, '摩羯座', '射手座'],
};
function signFromMonthDay(month, day) {
  const e = ZODIAC_BOUNDARY[month];
  if (!e) return '';
  return day >= e[0] ? e[1] : e[2];
}

// 首页/结果页展示用的「类型代号」
// - 星座：显示元素（火象/土象/风象/水象）
// - 其他维度：显示类型名（INTJ / 安全型 / 生产者 …）
function typeCodeOf(dimKey, r) {
  if (!r) return '';
  if (dimKey === 'zodiac') {
    return r.element || ZODIAC_ELEMENT[r.name || r.label] || '';
  }
  return r.name || r.type || '';
}

